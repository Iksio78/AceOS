use limine::request::FramebufferRequest;

#[derive(Clone, Copy)]
pub struct lfb {
    pub buffer_ptr: *mut u32,
    pub width: usize,
    pub height: usize,
    pub pitch: usize, // przesunięcie w u32
}

impl lfb {
    pub fn init(fr: &limine::request::FramebufferRequest) -> Option<Self> {
        if let Some(framebuffer_response) = fr.response() {
            if let Some(framebuffer) = framebuffer_response.framebuffers().first() {
                return Some(Self {
                    buffer_ptr: framebuffer.address() as *mut u32,
                    width: framebuffer.width as usize,
                    height: framebuffer.height as usize,
                    pitch: (framebuffer.pitch / 4) as usize, // bajty na piksele u32
                });
            }
        }
        None
    }

    /// Sprawdza, czy wskaźnik bazowy nie jest nullem i czy wymiary mają sens
    pub fn is_valid(&self) -> bool {
        !self.buffer_ptr.is_null() && self.width > 0 && self.height > 0
    }

    pub fn fill_screen(&self, color: u32) -> Result<(), &'static str> {
        if !self.is_valid() {
            return Err("You didn't initialize FrameBuffer");
        }

        // Liczymy łączną liczbę elementów u32 w buforze wideo
        let total_pixels = self.height * self.pitch;

        unsafe {
            for i in 0..total_pixels {
                self.buffer_ptr.add(i).write_volatile(color);
            }
        }

        Ok(())
    }

	pub unsafe fn draw_pixel(&self, x: usize, y: usize, color: u32 ) -> Result<(), &'static str> {
		if !self.is_valid() {
            return Err("You didn't initialize FrameBuffer");
        }

		if x >= self.width || y >= self.height{
			return Err("Out of bounds");
		}

		self.buffer_ptr.add(y * self.pitch + x).write_volatile(color);
		Ok(())
	}
}


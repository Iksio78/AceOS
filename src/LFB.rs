impl fmt::Write for FramebufferWriter {
    fn write_str(&mut self, s: &str) -> fmt::Result {
        // Blokujemy globalny LFB na czas zapisu tekstu
        let guard = crate::GLOBAL_LFB.lock();
        if let Some(lfb) = *guard {
            for c in s.chars() {
                if c == '\n' {
                    self.cursor_y += 16; // Wysokość standardowej linii czcionki
                    self.cursor_x = 0;
                } else {
                    let glyph = Self::get_glyph(c);

                    // Czcionka: 8x16, MSB -> lewy piksel.
                    // Rysujemy bezpośrednio do framebufferu, żeby nie robić
                    // 128 osobnych wywołań funkcji dla każdego znaku.
                    for row in 0..16 {
                        let bits = glyph[row];
                        let y = self.cursor_y + row;

                        if y >= lfb.height {
                            continue;
                        }

                        for col in 0..8 {
                            let x = self.cursor_x + col;

                            if x >= lfb.width {
                                continue;
                            }

                            let color = if (bits & (0x80 >> col)) != 0 {
                                self.fg_color
                            } else {
                                self.bg_color
                            };

                            unsafe {
                                lfb.buffer_ptr
                                    .add(y * lfb.pitch + x)
                                    .write_volatile(color);
                            }
                        }
                    }

                    self.cursor_x += 8;

                    // Przejście do następnej linii po dojściu do prawej krawędzi.
                    if self.cursor_x + 8 > lfb.width {
                        self.cursor_x = 0;
                        self.cursor_y += 16;
                    }

                    // Brak scrollowania na tym etapie: po dojściu do dołu
                    // zaczynamy ponownie od początku ekranu.
                    if self.cursor_y + 16 > lfb.height {
                        self.cursor_x = 0;
                        self.cursor_y = 0;
                    }
                }
            }
        }
        Ok(())
    }
}

